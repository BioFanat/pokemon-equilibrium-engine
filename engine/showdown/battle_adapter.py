"""Corrections at the pinned Foul Play / poke-engine boundary.

Keep these in our checkout rather than editing the separately installed client.
"""


def battle_to_poke_engine_state(battle):
    from fp.search.poke_engine_helpers import battle_to_poke_engine_state as convert
    import hidden as hd

    state = convert(battle)
    sides = []
    for side, battler in ((state.side_one, battle.user), (state.side_two, battle.opponent)):
        # Upstream copies the other five stages but hardcodes these two to 0.
        sides.append(hd.copy_side(
            side, accuracy_boost=battler.active.boosts.get("accuracy", 0),
            evasion_boost=battler.active.boosts.get("evasion", 0)))
    return hd.make_state(*sides, {f: getattr(state, f) for f in hd.GF})


def request_options(battle):
    """Our selectable action labels, or None when no request is available.

    Engine options remain an additional constraint (Encore, forced pivots,
    choice lock, etc.). Use IDs, never request indices: engine search reorders
    moves. maybeDisabled is uncertainty, not a server prohibition.
    """
    request = battle.request_json
    if not request:
        return None
    forced = bool(request.get("forceSwitch", [False])[0])
    active = (request.get("active") or [{}])[0]
    reviving = bool(getattr(battle.user.active, "reviving", False)) and forced
    options = []
    if forced or not active.get("trapped", False):
        for p in battle.user.reserve:
            if (p.hp <= 0) == reviving:
                options.append(p.name)
    if not forced and not battle.team_preview:
        moves = []
        for move in active.get("moves", []):
            if move.get("disabled", False) or move.get("pp", 1) <= 0:
                continue
            name = move["id"]
            if name == "hiddenpower":
                from fp.battle.helpers import normalize_name
                name = normalize_name(move["move"])
            moves.append(name)
        # Struggle is generated by the engine when no selectable moves remain.
        options.extend(moves or ["struggle"])
        if active.get("canTerastallize"):
            options.extend(m + "-tera" for m in (moves or ["struggle"]))
    return options


def raw_action(label, battle):
    """Canonical matrix label -> Foul Play's action string, by identity."""
    if any(p.name == label for p in battle.user.reserve):
        return "switch " + label
    return "No Move" if label == "none" else label
